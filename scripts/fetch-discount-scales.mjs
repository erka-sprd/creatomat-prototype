#!/usr/bin/env node
// Fetch the REAL volume-discount scales from Spreadshirt — one per product type
// — and write them into lib/volume-discount-scales.generated.ts.
//
// Why per product type: GET /shops/{shopId}/discountScales takes an optional
// `productTypeId` and returns a DIFFERENT scale depending on it. create-omat
// passes it (src/services/Shop.ts -> getDiscounts, via src/hooks/useDiscount.ts),
// so its volume-discount dialog shows product-specific tiers. This script bakes
// the same data in statically, since the prototype has no API layer.
//
// Run: `node scripts/fetch-discount-scales.mjs`

import { writeFile } from "node:fs/promises"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, "..")
const OUT_FILE = join(ROOT, "lib", "volume-discount-scales.generated.ts")

// The CYO shop create-omat's own tooling points at (DEFAULT_SHOP_ID in
// create-omat's .env.local).
const SHOP_ID = process.env.SHOP_ID || "1133169"
const API = "https://api.spreadshirt.net/api/v1"
const LOCALE = "en_GB"
const CATALOG_URL =
    process.env.NEXT_PUBLIC_CATALOG_URL || "https://product-catalog-five-self.vercel.app"

const json = async url => {
    const res = await fetch(url, { headers: { Accept: "application/json" } })
    if (!res.ok) throw new Error(`${res.status} ${res.statusText} — ${url}`)
    return res.json()
}

/** One scale (id + tiers), or null when the shop returns none. */
const fetchScale = async productTypeId => {
    const params = new URLSearchParams({
        fullData: "true",
        mediaType: "json",
        locale: LOCALE,
    })
    if (productTypeId) params.set("productTypeId", productTypeId)
    const data = await json(`${API}/shops/${SHOP_ID}/discountScales?${params}`)
    const scale = data.discountScales?.[0]
    if (!scale) return null
    // Same shaping as create-omat's getDiscounts: drop zero credits, sort by
    // the range start.
    const tiers = scale.discounts
        .filter(d => d.credit.value > 0)
        .sort((a, b) => a.valueRange.from - b.valueRange.from)
        .map(d => ({
            from: d.valueRange.from,
            to: d.valueRange.to ?? null,
            percentage: d.credit.value,
        }))
    return { scaleId: scale.id, tiers }
}

const main = async () => {
    const catalog = await json(`${CATALOG_URL}/catalog.json`)
    const products = catalog.products.map(p => ({ id: p.id, name: p.name }))
    console.log(`Catalogue: ${products.length} products`)

    const fallback = await fetchScale(null)
    if (!fallback) throw new Error(`Shop ${SHOP_ID} returned no default discount scale`)
    console.log(`Default scale ${fallback.scaleId} (${fallback.tiers.length} tiers)`)

    // Sequential on purpose — 32 products, and the API is happier without a burst.
    const byProduct = {}
    for (const product of products) {
        const scale = await fetchScale(product.id)
        if (!scale) {
            console.warn(`  ${product.id} ${product.name}: no scale, falls back to default`)
            continue
        }
        byProduct[product.id] = { ...scale, name: product.name }
        const top = scale.tiers[scale.tiers.length - 1]
        console.log(
            `  ${product.id.padEnd(5)} scale ${scale.scaleId.padEnd(4)} ` +
                `${scale.tiers.length} tiers, top ${top.from}+ = ${top.percentage}% — ${product.name}`
        )
    }

    const scaleLine = t =>
        `        { from: ${t.from}, to: ${t.to === null ? "null" : t.to}, percentage: ${t.percentage} },`

    const entries = Object.entries(byProduct)
        .map(
            ([id, scale]) =>
                `    // ${scale.name} — scale ${scale.scaleId}\n` +
                `    "${id}": [\n${scale.tiers.map(scaleLine).join("\n")}\n    ],`
        )
        .join("\n")

    const out = `// GENERATED by scripts/fetch-discount-scales.mjs — do not edit by hand.
// Source: GET ${API}/shops/${SHOP_ID}/discountScales?fullData=true&productTypeId={id}
// Shop ${SHOP_ID}, locale ${LOCALE}. Re-run the script to refresh.

import type { VolumeDiscountTier } from "./volume-discount"

/** Scale returned without a productTypeId — used for products not listed below. */
export const DEFAULT_VOLUME_DISCOUNT_TIERS: VolumeDiscountTier[] = [
${fallback.tiers.map(scaleLine).join("\n")}
]

/** Product type id -> its own scale. Real per-product data, not invented. */
export const VOLUME_DISCOUNT_TIERS_BY_PRODUCT: Record<string, VolumeDiscountTier[]> = {
${entries}
}
`
    await writeFile(OUT_FILE, out, "utf8")
    console.log(`\nWrote ${OUT_FILE}`)
}

main().catch(err => {
    console.error(err)
    process.exit(1)
})
